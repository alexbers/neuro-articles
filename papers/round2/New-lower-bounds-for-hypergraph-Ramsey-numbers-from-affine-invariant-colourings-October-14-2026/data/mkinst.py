#!/usr/bin/env python3
"""Generate instances for cayley.c.
  gf  q e      : additive group of GF(q), classes = cosets of the index-e subgroup of GF(q)^*;
                 normalizer perms: multiplication by primitive g, Frobenius.
  zn  n gens.. : Z_n, K = subgroup of Z_n^* generated by -1 and gens; normalizer = all units.
Writes binary: int32 n,e,np ; int32 reps[e]; int32 perms[np*e]; uint8 diffclass[n*n]
Also writes a .json sidecar with classes (element lists) for later decoding."""
import sys, struct, json, itertools
from math import gcd

def factor(n):
    f = {}; d = 2
    while d * d <= n:
        while n % d == 0:
            f[d] = f.get(d, 0) + 1; n //= d
        d += 1
    if n > 1: f[n] = f.get(n, 0) + 1
    return f

def prime_power(q):
    f = factor(q)
    if len(f) != 1: return None
    (p, m), = f.items(); return p, m

class GF:
    def __init__(self, q):
        p, m = prime_power(q); self.p, self.m, self.q = p, m, q
        # find primitive polynomial x^m - (c_{m-1} x^{m-1}+...+c_0) by brute force
        for coeffs in itertools.product(range(p), repeat=m):
            if coeffs[0] == 0: continue
            # element encoding: integer sum d_i p^i ; multiply by x
            def mulx(a):
                d = [(a // p**i) % p for i in range(m)]
                top = d[m - 1]
                nd = [0] + d[:m - 1]
                nd = [(nd[i] + top * coeffs[i]) % p for i in range(m)]
                return sum(nd[i] * p**i for i in range(m))
            # powers of x
            exp = []; a = 1; ok = True; seen = set()
            for k in range(q - 1):
                if a in seen: ok = False; break
                seen.add(a); exp.append(a); a = mulx(a)
            if ok and a == 1 and len(seen) == q - 1:
                self.exp = exp; break
        self.log = {a: k for k, a in enumerate(self.exp)}
        P = [p**i for i in range(m)]
        self.digits = [[(a // P[i]) % p for i in range(m)] for a in range(q)]
        self.P = P
    def add(self, a, b):
        da, db = self.digits[a], self.digits[b]
        return sum(((da[i] + db[i]) % self.p) * self.P[i] for i in range(self.m))
    def sub(self, a, b):
        da, db = self.digits[a], self.digits[b]
        return sum(((da[i] - db[i]) % self.p) * self.P[i] for i in range(self.m))
    def mul(self, a, b):
        if a == 0 or b == 0: return 0
        return self.exp[(self.log[a] + self.log[b]) % (self.q - 1)]

def closure(gens, e):
    ident = tuple(range(e)); G = {ident}; frontier = [ident]
    while frontier:
        nf = []
        for g in frontier:
            for h in gens:
                c = tuple(h[g[i]] for i in range(e))
                if c not in G: G.add(c); nf.append(c)
        frontier = nf
    return sorted(G)

def write(path, n, cls_of, reps, perms, subfn, classes, meta):
    e = len(reps)
    with open(path, 'wb') as f:
        f.write(struct.pack('<3i', n, e, len(perms)))
        f.write(struct.pack('<%di' % e, *reps))
        for p in perms: f.write(struct.pack('<%di' % e, *p))
        buf = bytearray(n * n)
        for x in range(n):
            for y in range(n):
                buf[x * n + y] = 255 if x == y else cls_of[subfn(x, y)]
        f.write(bytes(buf))
    meta = dict(meta); meta['classes'] = classes; meta['reps'] = reps
    with open(path.replace('.bin', '.json'), 'w') as f: json.dump(meta, f)

def gf_instance(q, e, path):
    F = GF(q); p = F.p
    assert (q - 1) % e == 0
    if p != 2: assert ((q - 1) // e) % 2 == 0, "need -1 in subgroup"
    cls_of = [255] * q
    classes = [[] for _ in range(e)]
    for a in range(1, q):
        c = F.log[a] % e; cls_of[a] = c; classes[c].append(a)
    reps = [F.exp[i] for i in range(e)]
    rot = [(i + 1) % e for i in range(e)]
    frob = [(p * i) % e for i in range(e)]
    perms = closure([rot, frob], e)
    write(path, q, cls_of, reps, perms, F.sub, classes, dict(kind='gf', q=q, e=e, p=p, m=F.m, exp=F.exp))

def zn_instance(n, gens, path):
    units = [u for u in range(1, n) if gcd(u, n) == 1]
    H = {1}; frontier = [1]; G0 = [n - 1] + list(gens)
    while frontier:
        nf = []
        for h in frontier:
            for g in G0:
                c = h * g % n
                if c not in H: H.add(c); nf.append(c)
        frontier = nf
    cls_of = [255] * n; classes = []
    for a in range(1, n):
        if cls_of[a] != 255: continue
        orb = sorted({a * h % n for h in H})
        for b in orb: cls_of[b] = len(classes)
        classes.append(orb)
    e = len(classes); reps = [c[0] for c in classes]
    # normalizer: unit multipliers permute H-orbits; take generators = all units mod H (just use all units, closure dedups)
    gens = []
    seenperm = set()
    for u in units:
        perm = tuple(cls_of[reps[i] * u % n] for i in range(e))
        if perm not in seenperm: seenperm.add(perm); gens.append(perm)
    perms = closure(gens, e)
    write(path, n, cls_of, reps, perms, lambda x, y: (x - y) % n, classes, dict(kind='zn', n=n, H=sorted(H)))

if __name__ == '__main__':
    kind = sys.argv[1]
    if kind == 'gf':
        q, e = int(sys.argv[2]), int(sys.argv[3]); gf_instance(q, e, sys.argv[4])
    elif kind == 'zn':
        n = int(sys.argv[2]); gens = [int(x) for x in sys.argv[3].split(',')] if sys.argv[3] != '-' else []
        zn_instance(n, gens, sys.argv[4])

def generic_instance(n, sub, kgens, ngens, path, meta):
    """n elements 0..n-1 (0 = identity); sub(x,y); kgens: automorphisms (lists) generating K (must make
    orbits closed under inversion); ngens: automorphisms normalizing K (permute K-orbits)."""
    cls_of = [255] * n; classes = []
    for a in range(1, n):
        if cls_of[a] != 255: continue
        orb = {a}; fr = [a]
        while fr:
            nf = []
            for x in fr:
                for g in kgens:
                    y = g[x]
                    if y not in orb: orb.add(y); nf.append(y)
            fr = nf
        for b in orb: cls_of[b] = len(classes)
        classes.append(sorted(orb))
    e = len(classes); assert e < 255
    reps = [c[0] for c in classes]
    # check inversion closure
    for c in classes:
        for x in c[:3]:
            assert cls_of[sub(0, x)] == cls_of[x], "orbits not closed under inversion"
    gens = []
    for g in ngens:
        perm = tuple(cls_of[g[reps[i]]] for i in range(e))
        gens.append(perm)
    perms = closure(gens, e) if gens else [tuple(range(e))]
    write(path, n, cls_of, reps, perms, sub, classes, meta)

def gfz_instance(q, e, t, path):
    """group GF(q) x Z_t ; element (a,j) -> a + q*j ; K = <mult by g^e on GF part, global negation>."""
    F = GF(q); p = F.p
    assert (q - 1) % e == 0
    if p != 2: assert ((q - 1) // e) % 2 == 0
    n = q * t
    def enc(a, j): return a + q * (j % t)
    def dec(x): return x % q, x // q
    neg_gf = [F.sub(0, a) for a in range(q)]
    def sub(x, y):
        a, j = dec(x); b, k = dec(y); return enc(F.sub(a, b), j - k)
    ge = F.exp[e % (q - 1)]
    mul_ge = [enc(F.mul(ge, dec(x)[0]), dec(x)[1]) for x in range(n)]
    neg = [enc(neg_gf[dec(x)[0]], -dec(x)[1]) for x in range(n)]
    g1 = F.exp[1 % (q - 1)]
    mul_g = [enc(F.mul(g1, dec(x)[0]), dec(x)[1]) for x in range(n)]
    frob = [enc(F.exp[(F.log[dec(x)[0]] * p) % (q - 1)] if dec(x)[0] else 0, dec(x)[1]) for x in range(n)]
    ngens = [mul_g, frob]
    for u in range(2, t):
        if gcd(u, t) == 1: ngens.append([enc(dec(x)[0], dec(x)[1] * u) for x in range(n)])
    generic_instance(n, sub, [mul_ge, neg], ngens, path, dict(kind='gfz', q=q, e=e, t=t, exp=F.exp))

if __name__ == '__main__' and sys.argv[1] == 'gfz':
    gfz_instance(int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), sys.argv[5])
